#!/usr/bin/env python3
"""Generate the one shared attribute enum. IDs are explicit, never inferred."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
schema = json.loads((ROOT/'schema/attributes.json').read_text())
entries = sorted(schema['attributes'], key=lambda a:a['id'])
for field in ['id','symbol','name']:
    assert len({a[field] for a in entries}) == len(entries), 'duplicate '+field
assert all(0 < a['id'] <= 0xffffffff for a in entries)
fingerprint = hashlib.sha256(json.dumps(schema,sort_keys=True,separators=(',',':')).encode()).hexdigest()
c_schema = f'// Generated by tool/generate_attributes.py. Edit schema/attributes.json.\n#ifndef DATAFRIEND_SCHEMA_H\n#define DATAFRIEND_SCHEMA_H\n#define DATAFRIEND_SCHEMA "{fingerprint}"\n#endif\n'
c_schema = c_schema.removesuffix('#endif\n')
c_schema += '#include <stdint.h>\n#include <stddef.h>\n#include <string.h>\n'
c_schema += 'enum df_attribute {\n'
c_schema += ''.join(f"  DF_ATTR_{re.sub(r'(?<!^)(?=[A-Z])', '_', a['symbol']).upper()} = {a['id']},\n" for a in entries)
c_schema += '};\n'
c_schema += 'typedef struct df_attribute_definition { uint32_t id; const char *name; } df_attribute_definition;\n'
c_schema += 'static const df_attribute_definition df_attributes[] = {\n'
c_schema += ''.join(f"  {{{a['id']}, {json.dumps(a['name'])}}},\n" for a in entries)
c_schema += '};\n#define DF_ATTRIBUTE_COUNT (sizeof(df_attributes)/sizeof(df_attributes[0]))\n'
c_schema += f"#define DF_ATTRIBUTE_LIMIT {max(a['id'] for a in entries)+1}\n"
c_schema += 'static inline size_t df_attribute_index(uint32_t id) {\n  switch(id) {\n'
c_schema += ''.join(f"    case {a['id']}: return {i};\n" for i,a in enumerate(entries))
c_schema += '    default: return DF_ATTRIBUTE_COUNT;\n  }\n}\n'
c_schema += '''static inline const char *df_attribute_name(uint32_t id) {
  size_t i=df_attribute_index(id);return i<DF_ATTRIBUTE_COUNT?df_attributes[i].name:NULL;
}
static inline uint32_t df_attribute_id(const void *name,size_t size) {
  for(size_t i=0;i<DF_ATTRIBUTE_COUNT;++i)if(strlen(df_attributes[i].name)==size&&(!size||!memcmp(df_attributes[i].name,name,size)))return df_attributes[i].id;
  return 0;
}
#endif
'''
outputs = {'schema.h':c_schema}
for relative, content in outputs.items():
    path = ROOT/relative
    if args.check:
        if not path.exists() or path.read_text()!=content:
            raise SystemExit('stale generated schema: '+relative)
    else:
        path.write_text(content)
